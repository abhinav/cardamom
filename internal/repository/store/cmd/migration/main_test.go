func TestGenerateMigration_sql(t *testing.T) {
	root := newMigrationRepository(t)
	now := time.Date(2026, time.July, 24, 1, 2, 3, 0, time.FixedZone("PDT", -7*60*60))

	path, err := generateMigration(root, migrationKindSQL, " Add user-status_2 ", now)
	require.NoError(t, err)
	assert.Equal(
		t,
		filepath.Join(
			"internal",
			"repository",
			"store",
			"migrations",
			"20260724080203_add_user_status_2.sql",
		),
		path,
	)

	body, err := os.ReadFile(filepath.Join(root, path))
	require.NoError(t, err)
	assert.Equal(t, `-- +goose Up

-- Replace this comment with the forward schema migration.
`, string(body))
}

func TestGenerateMigration_go(t *testing.T) {
	root := newMigrationRepository(t)
	now := time.Date(2026, time.July, 24, 8, 2, 3, 0, time.UTC)

	path, err := generateMigration(root, migrationKindGo, "Backfill issue status", now)
	require.NoError(t, err)
	assert.Equal(
		t,
		filepath.Join(
			"internal",
			"repository",
			"store",
			"migration_20260724080203_backfill_issue_status.go",
		),
		path,
	)

	body, err := os.ReadFile(filepath.Join(root, path))
	require.NoError(t, err)
	assert.Equal(t, `package store

import (
	"context"
	"database/sql"
	"errors"
)

func migrate20260724080203(context.Context, *sql.Tx) error {
	return errors.New("implement data migration")
}
`, string(body))

	registry, err := os.ReadFile(filepath.Join(
		root,
		"internal",
		"repository",
		"store",
		"go_migrations.go",
	))
	require.NoError(t, err)
	assert.Equal(t, `// Code generated by the migration authoring workflow. DO NOT EDIT.

package store

import "github.com/pressly/goose/v3"

// goMigrations is the complete data-only migration registry used during
// package initialization. Schema changes remain in SQL so the migration
// directory stays authoritative for sqlc.
var goMigrations = []*goose.Migration{
	goose.NewGoMigration(
		20260724080203,
		&goose.GoFunc{RunTx: migrate20260724080203},
		nil,
	),
}
`, string(registry))
}

func TestGenerateMigrationRejectsInvalidName(t *testing.T) {
	tests := []struct {
		name string
		give string
		want string
	}{
		{name: "Missing", give: "", want: "migration name is required"},
		{name: "Whitespace", give: " \t ", want: "migration name is required"},
		{name: "Path", give: "add/status", want: "invalid migration name"},
		{name: "Extension", give: "add.status", want: "invalid migration name"},
		{name: "LeadingSeparator", give: "-status", want: "invalid migration name"},
		{name: "NonASCII", give: "na\u00efve", want: "invalid migration name"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := newMigrationRepository(t)

			_, err := generateMigration(
				root,
				migrationKindSQL,
				tt.give,
				time.Date(2026, time.July, 24, 8, 2, 3, 0, time.UTC),
			)
			assert.ErrorContains(t, err, tt.want)
		})
	}
}

func TestGenerateMigrationRejectsSharedVersionCollision(t *testing.T) {
	now := time.Date(2026, time.July, 24, 8, 2, 3, 0, time.UTC)

	t.Run("SQLConflictsWithGo", func(t *testing.T) {
		root := newMigrationRepository(t)
		existing := filepath.Join(
			root,
			"internal",
			"repository",
			"store",
			"migration_20260724080203_existing.go",
		)
		require.NoError(t, os.WriteFile(existing, []byte("package store\n"), 0o644))

		path, err := generateMigration(root, migrationKindSQL, "new schema", now)
		assert.Empty(t, path)
		assert.ErrorContains(
			t,
			err,
			`migration version 20260724080203 already exists as "migration_20260724080203_existing.go"`,
		)
		assert.NoFileExists(t, filepath.Join(
			root,
			"internal",
			"repository",
			"store",
			"migrations",
			"20260724080203_new_schema.sql",
		))
	})

	t.Run("GoConflictsWithSQL", func(t *testing.T) {
		root := newMigrationRepository(t)
		existing := filepath.Join(
			root,
			"internal",
			"repository",
			"store",
			"migrations",
			"20260724080203_existing.sql",
		)
		require.NoError(t, os.WriteFile(existing, nil, 0o644))

		path, err := generateMigration(root, migrationKindGo, "new data", now)
		assert.Empty(t, path)
		assert.ErrorContains(
			t,
			err,
			`migration version 20260724080203 already exists as "20260724080203_existing.sql"`,
		)
		assert.NoFileExists(t, filepath.Join(
			root,
			"internal",
			"repository",
			"store",
			"migration_20260724080203_new_data.go",
		))
	})
}

func TestGenerateMigrationRebuildsCompleteGoRegistry(t *testing.T) {
	root := newMigrationRepository(t)
	require.NoError(t, os.WriteFile(
		filepath.Join(
			root,
			"internal",
			"repository",
			"store",
			"migration_20260725000000_later.go",
		),
		[]byte("package store\n"),
		0o644,
	))

	_, err := generateMigration(
		root,
		migrationKindGo,
		"earlier migration",
		time.Date(2026, time.July, 24, 8, 2, 3, 0, time.UTC),
	)
	require.NoError(t, err)

	registry, err := os.ReadFile(filepath.Join(
		root,
		"internal",
		"repository",
		"store",
		"go_migrations.go",
	))
	require.NoError(t, err)
	assert.Equal(t, `// Code generated by the migration authoring workflow. DO NOT EDIT.

package store

import "github.com/pressly/goose/v3"

// goMigrations is the complete data-only migration registry used during
// package initialization. Schema changes remain in SQL so the migration
// directory stays authoritative for sqlc.
var goMigrations = []*goose.Migration{
	goose.NewGoMigration(
		20260724080203,
		&goose.GoFunc{RunTx: migrate20260724080203},
		nil,
	),
	goose.NewGoMigration(
		20260725000000,
		&goose.GoFunc{RunTx: migrate20260725000000},
		nil,
	),
}
`, string(registry))
}

func TestGenerateMigrationRestoresGoRegistryAfterSourceFailure(t *testing.T) {
	root := newMigrationRepository(t)
	storeDir := filepath.Join(root, "internal", "repository", "store")
	registryPath := filepath.Join(storeDir, "go_migrations.go")
	originalRegistry, err := os.ReadFile(registryPath)
	require.NoError(t, err)
	require.NoError(t, os.Mkdir(filepath.Join(
		storeDir,
		"migration_20260724080203_new_data.go",
	), 0o755))

	_, err = generateMigration(
		root,
		migrationKindGo,
		"new data",
		time.Date(2026, time.July, 24, 8, 2, 3, 0, time.UTC),
	)
	assert.ErrorContains(t, err, "create migration")
	registry, err := os.ReadFile(registryPath)
	require.NoError(t, err)
	assert.Equal(t, originalRegistry, registry)
}

func newMigrationRepository(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	storeDir := filepath.Join(root, "internal", "repository", "store")
	require.NoError(t, os.MkdirAll(filepath.Join(storeDir, "migrations"), 0o755))
	require.NoError(t, os.WriteFile(
		filepath.Join(storeDir, "go_migrations.go"),
		[]byte(`// Code generated by the migration authoring workflow. DO NOT EDIT.

package store

import "github.com/pressly/goose/v3"

// goMigrations is the complete data-only migration registry used during
// package initialization. Schema changes remain in SQL so the migration
// directory stays authoritative for sqlc.
var goMigrations = []*goose.Migration{}
`),
		0o644,
	))
	return root
}
